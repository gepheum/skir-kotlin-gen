// A companion generator that references every declaration emitted by
// skir-kotlin-gen through its symbol provider. Compiling the e2e test sources
// checks that the provider agrees with generateCode.
import { GENERATOR as KOTLIN } from "../dist/index.js";

export const GENERATOR = {
  id: "symbols-check",
  configType: KOTLIN.configType,
  generateCode(input) {
    const symbols = KOTLIN.symbols(input);
    const records = [];
    const methods = [];
    const rebuilds = [];
    for (const module of input.modules) {
      for (const location of module.records) {
        const record = symbols.record(location).reference;
        records.push(`${record}::class,\n`);
        if (location.record.recordType !== "enum") {
          continue;
        }
        const arms = location.record.fields.map((variant) => {
          const constructor = symbols.variantConstructor(location, variant);
          const value = variant.type
            ? symbols.variantValue(location, variant).reference
            : "";
          const rebuilt = constructor.reference.replace(
            "{value}",
            value.replace("{value}", "this"),
          );
          return `${symbols.variant(location, variant).reference} -> ${rebuilt}\n`;
        });
        rebuilds.push(
          `fun ${record}.rebuild(): ${record} =\n`,
          "when (kind) {\n",
          ...arms,
          "else -> this\n",
          "}\n\n",
        );
      }
      for (const method of module.methods) {
        methods.push(`${symbols.method(module, method).reference},\n`);
      }
    }
    const code = [
      '@file:Suppress("ktlint")\n\n',
      "// Generated by e2e-test/symbols_check.mjs\n\n",
      "package symbols_check\n\n",
      "val records: List<kotlin.reflect.KClass<*>> = listOf(\n",
      ...records,
      ")\n\n",
      "val methods: List<kotlin.Any> = listOf(\n",
      ...methods,
      ")\n\n",
      "/** Rebuilds the variant from its own value, through the symbol provider. */\n",
      ...rebuilds,
    ].join("");
    return { files: [{ path: "symbols_check.kt", code }] };
  },
};
